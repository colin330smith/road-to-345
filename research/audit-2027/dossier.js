// Program dossier: what the plan prescribes, computed from the engine itself (default spec, default gates).
// Usage, from the repo root: node research/audit-2027/dossier.js   -> writes dossier.md and dossier.json here.
const path = require("path"), fs = require("fs");
const E = require(path.join(__dirname, "..", "..", "engine.js")), G = require(path.join(__dirname, "..", "..", "goals.js")), N = require(path.join(__dirname, "..", "..", "nutrition.js"));
const SPEC = E.DEFAULT_SPEC, DAY = ["", "Mon", "Tue", "Wed", "Thu", "Fri", "Sat", "Sun"];
const dk = (t) => new Date(t).toISOString().slice(0, 10);
const LOG = ["accessory", "single", "backoff", "paused", "ohp"];
const filler = (b) => /FILLER|PRIMER/.test(b.cap || "");
// the test suite's own clock (test.js "Wave 4+ budget")
const cost = (b) => filler(b) ? 0 : b.type === "single" ? 4 : b.type === "backoff" && E.LIFTS.includes(b.lift) ? b.sets * 3.5
  : b.type === "paused" || b.type === "ohp" ? b.sets * 3 : b.type === "backoff" ? b.sets * 2.5 : b.type === "accessory" ? b.sets * (b.db ? 2 : 1.75)
  : b.type === "warmup" ? 8 : b.type === "conditioning" ? 18 : b.type === "cooldown" ? 5 : 0;
const out = [], J = { waves: {}, weeks: {} };
const P = (s = "") => out.push(s);
const pct = (w, base) => (base ? Math.round((w / base) * 1000) / 10 : null);

P("# Program dossier — Road to 3/4/5 (Model 2), computed from engine.js");
P("");
P("Generated by `node research/audit-2027/dossier.js` on the default spec " + JSON.stringify(SPEC) + " with default (projected, small-step) gates and no logs. Loads are what the engine prescribes with no logged history: real loads follow his logged sets (Rules A–D), so read the STRUCTURE (sets, reps, RPE, % of base, exercises, order, weekly sets per muscle), not the absolute accessory weights.");
P("");
P("## 1. Calendar and projected bases (default small-step pace: +2.5 bench, +5 squat and deadlift per 4-week wave)");
P("");
P("| Wave | Starts (Mon) | Cycle | Bench base | Squat base | Deadlift base |");
P("|---|---|---|---|---|---|");
for (let w = 4; w <= 19; w++) { const cb = E.cbFor(w); J.waves[w] = { start: dk(E.waveStartUTC(w, 0)), cycle: E.CYCLE_NAME[E.cycleOf(w)], cb }; P(`| ${w} | ${dk(E.waveStartUTC(w, 0))} | ${E.CYCLE_NAME[E.cycleOf(w)]} | ${cb.bn} | ${cb.sq} | ${cb.dl} |`); }
P("");
P(`ETA wave for the goal bases on that pace (engine \`etaWave\`): bench 315 → Wave ${E.etaWave("bn", 315)}, squat 405 → Wave ${E.etaWave("sq", 405)}, deadlift 495 → Wave ${E.etaWave("dl", 495)} (Wave 25 starts ${dk(E.waveStartUTC(25, 0))}, Wave 27 ${dk(E.waveStartUTC(27, 0))}).`);
P(`A "base" (CB) is the cycle's training max the percentages run from; Wave 3 bases were set from measured lifts (bench 255, squat 295, deadlift 385 in Sep 2026). Each wave's gate moves a base by: clean +5 bench / +10 squat and deadlift, small +2.5 / +5 (the projection default), repeat 0, reset −5%. Rule D sets the gate from the rated top singles when he does not (cut-offs on the single's implied max vs the model: ${JSON.stringify(E.GATE_CUTS)}).`);
P(`Test days: Wave 6 week 4 Friday = ${dk(E.sessionDayUTC(6, 4, 5, 0))} (max test); Wave 12 week 4 Friday = ${dk(E.sessionDayUTC(12, 4, 5, 0))} (the summer-2027 meet slot); Wave 18 = ${dk(E.sessionDayUTC(18, 4, 5, 0))}.`);
P("");

const mainRow = (b, cb) => {
  const base = b.lift && cb[b.lift] ? cb[b.lift] : null;
  return `${b.name}: ${b.sets}×${b.reps} @ ${b.disp != null ? b.disp : b.w}${base ? ` (${pct(b.w, base)}% of base)` : ""} · RPE ${b.rpe}`;
};
P("## 2. Main and tracked lifts, week by week (Waves 5–12: now → the January test → the June 2027 meet)");
P("");
for (let w = 5; w <= 12; w++) {
  const cb = E.cbFor(w);
  P(`### Wave ${w} — ${E.CYCLE_NAME[E.cycleOf(w)]} (starts ${dk(E.waveStartUTC(w, 0))}) · bases bench ${cb.bn} / squat ${cb.sq} / deadlift ${cb.dl}`);
  for (let wk = 1; wk <= 4; wk++) {
    P(`- **Week ${wk}**`);
    for (let d = 1; d <= 7; d++) {
      const s = E.sessionFor(w, wk, d, {}, SPEC), mains = s.filter((b) => ["single", "backoff", "paused", "ohp", "test"].includes(b.type));
      if (!mains.length) continue;
      P(`  - ${DAY[d]}: ` + mains.map((b) => b.type === "test" ? `TEST: ${b.name}` : mainRow(b, cb)).join(" · "));
    }
  }
  P("");
}

P("## 3. Full sessions (every block, in order) — one week per cycle type");
P("");
P("`[F]` = last set taken to failure / RPE 9–10 (lastHard) · `[LP]` = lengthened partials after the last set · `(filler)` = superset into main-lift rests, off the clock · est. min uses the test suite's clock (warm-up 8, single 4, main back-off set 3.5, paused/OHP 3, tracked back-off 2.5, accessory 1.75–2, conditioning 18, cooldown 5).");
P("");
const showWeek = (w, wk) => {
  P(`### Wave ${w} week ${wk} — ${E.CYCLE_NAME[E.cycleOf(w)]}`);
  const all = [];
  for (let d = 1; d <= 7; d++) {
    const s = E.sessionFor(w, wk, d, {}, SPEC); all.push(...s);
    const work = s.filter((b) => LOG.includes(b.type) && !filler(b)).reduce((a, b) => a + b.sets, 0), min = Math.round(s.reduce((a, b) => a + cost(b), 0));
    if (!s.length) { P(`- **${DAY[d]}**: rest`); continue; }
    P(`- **${DAY[d]}** — ${work} working sets · est. ${min} min`);
    for (const b of s) {
      if (b.type === "warmup") P(`  - warm-up: ${b.rows.map((r) => `${r[0]}×${r[1]}`).join(", ")}`);
      else if (b.type === "cooldown" || b.type === "conditioning" || b.type === "spechead") P(`  - ${b.type}: ${b.name}${b.note ? ` — ${String(b.note).slice(0, 160)}` : ""}`);
      else if (b.type === "test") P(`  - TEST: ${b.name}${b.note ? ` — ${String(b.note).replace(/\s+/g, " ").slice(0, 700)}` : ""}${b.attempts ? ` · attempts ${JSON.stringify(b.attempts)}` : ""}`);
      else P(`  - ${b.name}: ${b.sets}×${b.reps} @ ${b.disp != null ? b.disp : b.w} · RPE ${b.rpe}${b.lastHard ? " [F]" : ""}${b.lp ? " [LP]" : ""}${filler(b) ? " (filler)" : ""}`);
    }
  }
  const ms = G.muscleSets(all);
  P(`- **Weekly fractional sets per muscle** (direct 1, a compound's secondary muscles 0.5): ` + Object.entries(ms).map(([k, v]) => `${G.MUSCLES[k].n} ${v}`).join(" · "));
  P("");
};
for (const [w, wk] of [[5, 2], [5, 3], [5, 4], [6, 1], [6, 3], [6, 4], [7, 1], [7, 3], [7, 4], [8, 1], [9, 1], [10, 1], [11, 1], [12, 1], [12, 4]]) showWeek(w, wk);

P("## 4. Weekly fractional sets per muscle, every week of Waves 5–12");
P("");
const mk = Object.keys(G.MUSCLES);
P("| Wave.wk | Cycle | " + mk.map((k) => G.MUSCLES[k].n).join(" | ") + " | Failure sets | Working sets | Minutes Mon–Sat |");
P("|---|---|" + mk.map(() => "---").join("|") + "|---|---|---|");
for (let w = 5; w <= 12; w++) for (let wk = 1; wk <= 4; wk++) {
  const all = [], mins = [];
  for (let d = 1; d <= 7; d++) { const s = E.sessionFor(w, wk, d, {}, SPEC); all.push(...s); if (d <= 6) mins.push(Math.round(s.reduce((a, b) => a + cost(b), 0))); }
  const ms = G.muscleSets(all), hard = all.filter((b) => b.lastHard).length, work = all.filter((b) => LOG.includes(b.type) && !filler(b)).reduce((a, b) => a + b.sets, 0);
  J.weeks[`${w}.${wk}`] = { muscles: ms, hard, work, mins };
  P(`| ${w}.${wk} | ${E.CYCLE_NAME[E.cycleOf(w)]} | ` + mk.map((k) => ms[k]).join(" | ") + ` | ${hard} | ${work} | ${mins.join(" / ")} |`);
}
P("");
P("## 5. Exposure frequency per muscle (days per week with at least one direct set), Wave 7 week 1");
P("");
{ const days = {}; for (const k of mk) days[k] = new Set();
  for (let d = 1; d <= 7; d++) for (const b of E.sessionFor(7, 1, d, {}, SPEC)) { if (!LOG.includes(b.type) || !b.sets) continue; for (const [m, c] of Object.entries(G.muscleRule(b.name))) if (c >= 1) days[m].add(DAY[d]); }
  P(mk.map((k) => `${G.MUSCLES[k].n}: ${[...days[k]].join("/") || "—"}`).join(" · ")); }
P("");
P("## 6. Nutrition modes (nutrition.js)");
P("");
for (const [k, m] of Object.entries(N.MODES)) P(`- ${m.label}: ${m.kcal} kcal · P ${m.p} / F ${m.f} / C ${m.c} · ${m.rate}`);
P(`- Maintenance is measured (rolling ${N.EST.full} days, provisional at ${N.EST.prov}); TRIM = measured − 500, GAIN = measured + 125. No trims in Cycles 5–6 (windows: ${E.noTrimWindows(0).map((b) => `${b.from}→${b.to}`).join(", ")}).`);
P(`- A sample MAINTAIN shift day: ` + N.dayPlan("shift", 2800, "2026-11-24").items.map((x) => `${x.time} ${x.meal.name} (${x.meal.kcal} kcal, ${x.meal.p}P)`).join(" · "));
fs.writeFileSync(path.join(__dirname, "dossier.md"), out.join("\n") + "\n");
fs.writeFileSync(path.join(__dirname, "dossier.json"), JSON.stringify(J, null, 1));
console.log(`dossier.md: ${out.length} lines`);
